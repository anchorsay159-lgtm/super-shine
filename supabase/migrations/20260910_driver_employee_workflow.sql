  update public.order_live_locations set status='completed',ended_at=now(),updated_at=now()
    where task_id=p_task_id and status='active';
  insert into public.driver_task_events(task_id,order_id,actor_id,actor_role,action,previous_status,new_status,metadata)
  values(p_task_id,v_order.id,auth.uid(),'driver','task_completed','arrived','completed',jsonb_build_object('verification','customer_code'));
  return public.driver_task_payload_v1(p_task_id,false);
end;
