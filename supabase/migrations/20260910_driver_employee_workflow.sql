  if not found then raise exception 'TASK_NOT_FOUND'; end if;
  if v_task.task_status = 'completed' then return public.driver_task_payload_v1(p_task_id,false); end if;
  if v_task.task_status <> 'arrived' then raise exception 'ARRIVAL_REQUIRED'; end if;
  select * into v_verify from public.driver_task_verifications where task_id=p_task_id for update;
  if v_verify.locked_until is not null and v_verify.locked_until > now() then
    return jsonb_build_object('error','CODE_TEMPORARILY_LOCKED','lockedUntil',v_verify.locked_until);
  end if;
  if v_verify.verification_code <> trim(coalesce(p_verification_code,'')) then
    update public.driver_task_verifications set failed_attempts=failed_attempts+1,
      locked_until=case when failed_attempts+1 >= 5 then now()+interval '10 minutes' else null end where task_id=p_task_id;
    insert into public.driver_task_events(task_id,order_id,actor_id,actor_role,action,previous_status,new_status,metadata)
    values(p_task_id,v_task.order_id,auth.uid(),'driver','verification_failed',v_task.task_status,v_task.task_status,
