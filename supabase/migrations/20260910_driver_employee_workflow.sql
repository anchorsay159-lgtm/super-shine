    return jsonb_build_object('error','INVALID_VERIFICATION_CODE','remainingAttempts',greatest(0,5-(v_verify.failed_attempts+1)));
  end if;
  update public.driver_task_verifications set verified_at=now(),failed_attempts=0,locked_until=null where task_id=p_task_id;
  select * into v_order from public.orders where id=v_task.order_id for update;
  if (v_task.task_type='pickup' and v_order.status<>'pickup_in_progress') or (v_task.task_type='delivery' and v_order.status<>'out_for_delivery') then
    raise exception 'ORDER_NOT_READY_FOR_COMPLETION';
  end if;
  update public.driver_tasks set task_status='completed',completed_at=now(),updated_at=now() where id=p_task_id;
  update public.orders set status=case when v_task.task_type='pickup' then 'picked_up' else 'delivered' end,
    status_comment=case when v_task.task_type='pickup' then 'Pickup confirmed by driver' else 'Delivery confirmed by driver' end,
