create or replace function public.admin_drivers_list_v1()
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v_result jsonb;
begin
  if not public.is_admin() then raise exception 'ADMIN_REQUIRED'; end if;
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', p.id, 'name', p.full_name, 'email', p.email, 'phone', p.phone,
    'activeTaskCount', (select count(*) from public.driver_tasks t where t.driver_id = p.id and t.task_status in ('assigned','accepted','en_route','arrived'))
  ) order by p.full_name, p.email), '[]'::jsonb) into v_result
  from public.profiles p where p.role = 'driver';
  return v_result;
end;
$$;

create or replace function public.admin_driver_operations_v1()
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v_result jsonb;
begin
  if not public.is_admin() then raise exception 'ADMIN_REQUIRED'; end if;
  select jsonb_build_object(
    'drivers', public.admin_drivers_list_v1(),
    'tasks', coalesce((select jsonb_agg(public.driver_task_payload_v1(t.id, true) order by
      case when t.task_status = 'unassigned' then 0 when exists(select 1 from public.driver_task_issues i where i.task_id=t.id and i.status='open') then 1 else 2 end,
      t.scheduled_for nulls last, t.created_at)
      from public.driver_tasks t where t.task_status not in ('completed','cancelled')), '[]'::jsonb),
    'issues', coalesce((select jsonb_agg(jsonb_build_object(
      'id', i.id, 'taskId', i.task_id, 'orderId', i.order_id, 'orderNumber', o.order_number,
      'driverId', i.driver_id, 'driverName', p.full_name, 'reason', i.reason,
      'notes', i.notes, 'status', i.status, 'createdAt', i.created_at
    ) order by i.created_at desc) from public.driver_task_issues i
      join public.orders o on o.id=i.order_id join public.profiles p on p.id=i.driver_id
      where i.status='open'), '[]'::jsonb)
  ) into v_result;
  return v_result;
end;
$$;

create or replace function public.admin_assign_driver_task_v1(
  p_task_id uuid, p_driver_id uuid, p_reason text default ''
) returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v_task public.driver_tasks%rowtype; v_old_driver uuid;
begin
  if not public.is_admin() then raise exception 'ADMIN_REQUIRED'; end if;
  if not exists(select 1 from public.profiles where id=p_driver_id and role='driver') then raise exception 'DRIVER_NOT_FOUND'; end if;
  select * into v_task from public.driver_tasks where id=p_task_id for update;
  if not found then raise exception 'TASK_NOT_FOUND'; end if;
  if v_task.task_status in ('completed','cancelled') then raise exception 'TASK_CLOSED'; end if;
  v_old_driver := v_task.driver_id;
  if v_old_driver is not null and v_old_driver <> p_driver_id and length(trim(coalesce(p_reason,''))) < 3 then
    raise exception 'REASSIGN_REASON_REQUIRED';
  end if;
  if v_old_driver is distinct from p_driver_id then
    update public.order_live_locations set status='completed', ended_at=now(), updated_at=now()
    where task_id=p_task_id and status='active';
    update public.driver_tasks set driver_id=p_driver_id, task_status='assigned', assigned_at=now(),
      accepted_at=null, started_at=null, arrived_at=null, updated_at=now() where id=p_task_id;
    update public.orders set assigned_driver_id=p_driver_id, updated_at=now() where id=v_task.order_id;
    insert into public.driver_task_events(task_id,order_id,actor_id,actor_role,action,previous_status,new_status,reason,metadata)
    values(p_task_id,v_task.order_id,auth.uid(),'admin',case when v_old_driver is null then 'driver_assigned' else 'driver_reassigned' end,
      v_task.task_status,'assigned',trim(coalesce(p_reason,'')),jsonb_build_object('previousDriverId',v_old_driver,'driverId',p_driver_id));
    if v_old_driver is not null then
