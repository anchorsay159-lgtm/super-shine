create or replace function public.driver_complete_task_v1(p_task_id uuid, p_verification_code text)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v_task public.driver_tasks%rowtype; v_order public.orders%rowtype; v_verify public.driver_task_verifications%rowtype;
begin
  if not public.is_driver() then raise exception 'DRIVER_REQUIRED'; end if;
