begin
  if not public.is_admin() then raise exception 'ADMIN_REQUIRED'; end if;
  if length(trim(coalesce(p_reason,''))) < 3 then raise exception 'OVERRIDE_REASON_REQUIRED'; end if;
  select * into v_task from public.driver_tasks where id=p_task_id for update;
  if not found then raise exception 'TASK_NOT_FOUND'; end if;
  if v_task.task_status='completed' then return public.driver_task_payload_v1(p_task_id,true); end if;
