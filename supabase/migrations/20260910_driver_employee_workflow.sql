begin;

-- Driver work is deliberately modelled separately from the laundry order.
-- Orders describe the customer's laundry journey; tasks describe one employee trip.
create table if not exists public.driver_tasks (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  driver_id uuid references public.profiles(id) on delete set null,
  task_type text not null check (task_type in ('pickup', 'delivery')),
  task_status text not null default 'unassigned' check (task_status in (
    'unassigned', 'assigned', 'accepted', 'en_route', 'arrived',
    'completed', 'cancelled', 'failed'
  )),
  scheduled_for timestamptz,
  assigned_at timestamptz,
  accepted_at timestamptz,
  started_at timestamptz,
  arrived_at timestamptz,
  completed_at timestamptz,
  cancelled_at timestamptz,
  failed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint driver_tasks_order_leg_unique unique (order_id, task_type)
);

create index if not exists driver_tasks_driver_queue_idx
  on public.driver_tasks(driver_id, task_status, scheduled_for, created_at);
create index if not exists driver_tasks_admin_queue_idx
  on public.driver_tasks(task_status, scheduled_for, created_at);

-- Codes are isolated from driver-readable task rows. Drivers can submit a code
-- to the completion RPC, but cannot query the expected value.
create table if not exists public.driver_task_verifications (
  task_id uuid primary key references public.driver_tasks(id) on delete cascade,
  verification_code text not null check (verification_code ~ '^[0-9]{4}$'),
  failed_attempts integer not null default 0 check (failed_attempts >= 0),
  locked_until timestamptz,
  verified_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.driver_task_events (
  id bigint generated by default as identity primary key,
  task_id uuid not null references public.driver_tasks(id) on delete cascade,
  order_id uuid not null references public.orders(id) on delete cascade,
  actor_id uuid references public.profiles(id) on delete set null,
  actor_role text not null check (actor_role in ('admin', 'driver', 'customer', 'system')),
  action text not null,
  previous_status text,
  new_status text,
  reason text not null default '',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists driver_task_events_task_created_idx
  on public.driver_task_events(task_id, created_at desc);

create table if not exists public.driver_task_issues (
  id uuid primary key default gen_random_uuid(),
  task_id uuid not null references public.driver_tasks(id) on delete cascade,
  order_id uuid not null references public.orders(id) on delete cascade,
  driver_id uuid not null references public.profiles(id) on delete restrict,
  reason text not null,
  notes text not null default '',
  status text not null default 'open' check (status in ('open', 'resolved')),
  resolved_by uuid references public.profiles(id) on delete set null,
  resolution_note text not null default '',
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists driver_task_issues_admin_queue_idx
  on public.driver_task_issues(status, created_at desc);

alter table public.order_live_locations
  add column if not exists task_id uuid references public.driver_tasks(id) on delete set null;
create index if not exists order_live_locations_task_idx
  on public.order_live_locations(task_id) where task_id is not null;

create or replace function public.is_driver()
returns boolean language sql stable security definer set search_path = public, pg_temp as $$
  select exists(select 1 from public.profiles where id = auth.uid() and role = 'driver');
$$;
revoke all on function public.is_driver() from public, anon;
grant execute on function public.is_driver() to authenticated;

-- Client profile writes may change contact/preferences, never privileges.
-- Server-side service-role provisioning has no auth.uid() and remains available.
create or replace function public.protect_profile_role_v1()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if tg_op = 'INSERT' and coalesce(auth.jwt() ->> 'role','') <> 'service_role' then
    new.role := 'customer';
    new.is_demo := coalesce((auth.jwt() ->> 'is_anonymous')::boolean, false);
  elsif coalesce(auth.jwt() ->> 'role','') <> 'service_role'
    and (new.role is distinct from old.role or new.is_demo is distinct from old.is_demo) then
    raise exception 'ROLE_CHANGE_FORBIDDEN';
  end if;
  return new;
end;
$$;
revoke all on function public.protect_profile_role_v1() from public, anon, authenticated;
drop trigger if exists profiles_protect_role_insert_v1 on public.profiles;
create trigger profiles_protect_role_insert_v1 before insert on public.profiles
for each row execute function public.protect_profile_role_v1();
drop trigger if exists profiles_protect_role_v1 on public.profiles;
create trigger profiles_protect_role_v1 before update of role,is_demo on public.profiles
for each row execute function public.protect_profile_role_v1();

alter table public.driver_tasks enable row level security;
alter table public.driver_task_verifications enable row level security;
alter table public.driver_task_events enable row level security;
alter table public.driver_task_issues enable row level security;

drop policy if exists "driver_tasks_participant_read_v1" on public.driver_tasks;
create policy "driver_tasks_participant_read_v1" on public.driver_tasks for select to authenticated using (
  public.is_admin() or driver_id = auth.uid() or exists (
    select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid()
  )
);
drop policy if exists "driver_task_verifications_customer_admin_read_v1" on public.driver_task_verifications;
create policy "driver_task_verifications_customer_admin_read_v1" on public.driver_task_verifications for select to authenticated using (
  public.is_admin() or exists (
    select 1 from public.driver_tasks t join public.orders o on o.id = t.order_id
    where t.id = task_id and o.user_id = auth.uid()
  )
);
drop policy if exists "driver_task_events_participant_read_v1" on public.driver_task_events;
create policy "driver_task_events_participant_read_v1" on public.driver_task_events for select to authenticated using (
  public.is_admin() or exists (
    select 1 from public.driver_tasks t join public.orders o on o.id = t.order_id
    where t.id = task_id and (t.driver_id = auth.uid() or o.user_id = auth.uid())
  )
);
drop policy if exists "driver_task_issues_participant_read_v1" on public.driver_task_issues;
create policy "driver_task_issues_participant_read_v1" on public.driver_task_issues for select to authenticated using (
  public.is_admin() or driver_id = auth.uid()
);

-- Writes are transaction-only. No client role can manufacture assignments,
-- promote itself, alter task history, or bypass verification.
revoke insert, update, delete on public.driver_tasks from anon, authenticated;
revoke insert, update, delete on public.driver_task_verifications from anon, authenticated;
revoke insert, update, delete on public.driver_task_events from anon, authenticated;
revoke insert, update, delete on public.driver_task_issues from anon, authenticated;
grant select on public.driver_tasks, public.driver_task_events, public.driver_task_issues to authenticated;
grant select on public.driver_task_verifications to authenticated;

create or replace function public.driver_task_schedule_v1(p_order public.orders)
returns timestamptz language sql stable set search_path = public, pg_temp as $$
  select case
    when p_order.pickup_date is not null and p_order.pickup_start is not null then
      ((p_order.pickup_date::text || ' ' || p_order.pickup_start::text)::timestamp at time zone 'Asia/Bangkok')
    else null
  end;
$$;

create or replace function public.create_driver_task_v1(p_order_id uuid, p_task_type text)
returns uuid language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_order public.orders%rowtype;
  v_task_id uuid;
begin
  if p_task_type not in ('pickup', 'delivery') then raise exception 'INVALID_TASK_TYPE'; end if;
  select * into v_order from public.orders where id = p_order_id;
  if not found or v_order.is_demo then return null; end if;
  if p_task_type = 'pickup' and v_order.collection_method <> 'home_pickup' then return null; end if;
  if p_task_type = 'delivery' and v_order.return_method <> 'home_delivery' then return null; end if;

  insert into public.driver_tasks(order_id, task_type, scheduled_for)
  values (
    p_order_id,
    p_task_type,
    case when p_task_type = 'pickup' then public.driver_task_schedule_v1(v_order) else v_order.delivery_eta end
  )
  on conflict (order_id, task_type) do nothing
  returning id into v_task_id;

  if v_task_id is not null then
    insert into public.driver_task_verifications(task_id, verification_code)
    values (v_task_id, lpad(floor(random() * 10000)::integer::text, 4, '0'));
    insert into public.driver_task_events(task_id, order_id, actor_role, action, new_status)
    values (v_task_id, p_order_id, 'system', 'task_created', 'unassigned');
  else
    select id into v_task_id from public.driver_tasks where order_id = p_order_id and task_type = p_task_type;
  end if;
  return v_task_id;
end;
$$;
revoke all on function public.create_driver_task_v1(uuid,text) from public, anon, authenticated;

create or replace function public.sync_driver_tasks_from_order_v1()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_task_id uuid;
  v_driver_id uuid;
  v_scheduled_for timestamptz;
begin
  if new.is_demo then return new; end if;
  if new.collection_method = 'home_pickup' and new.status in (
    'accepted','pickup_in_progress','picked_up','received_at_store','processing','ready',
    'ready_for_collection','out_for_delivery','delivered','collected'
  ) then
    v_task_id := public.create_driver_task_v1(new.id, 'pickup');
  end if;
  if new.return_method = 'home_delivery' and new.status in ('ready','out_for_delivery','delivered') then
    v_task_id := public.create_driver_task_v1(new.id, 'delivery');
  end if;

  -- Keep the assigned employee's schedule in sync without creating a second task.
  if new.collection_method = 'home_pickup' then
    v_scheduled_for := public.driver_task_schedule_v1(new);
    v_task_id := null;
    v_driver_id := null;
    update public.driver_tasks set scheduled_for=v_scheduled_for,updated_at=now()
    where order_id=new.id and task_type='pickup' and task_status not in ('completed','cancelled')
      and scheduled_for is distinct from v_scheduled_for
    returning id,driver_id into v_task_id,v_driver_id;
    if v_task_id is not null and v_driver_id is not null and tg_op='UPDATE' then
      insert into public.notifications(user_id,order_id,title,body,type,link,message_params,source_event_key)
      values(v_driver_id,new.id,'Pickup schedule changed','The pickup schedule for order '||new.order_number||' was updated.',
        'driver_task_schedule_changed','/driver/task/'||v_task_id,
        jsonb_build_object('orderNumber',new.order_number,'taskType','pickup','scheduledFor',v_scheduled_for),
        'driver-task-schedule:'||v_task_id::text||':'||extract(epoch from clock_timestamp())::bigint::text)
      on conflict (user_id,order_id,source_event_key) where source_event_key is not null and order_id is not null do nothing;
    end if;
  end if;
  if new.return_method = 'home_delivery' then
    v_scheduled_for := new.delivery_eta;
    v_task_id := null;
    v_driver_id := null;
    update public.driver_tasks set scheduled_for=v_scheduled_for,updated_at=now()
    where order_id=new.id and task_type='delivery' and task_status not in ('completed','cancelled')
      and scheduled_for is distinct from v_scheduled_for
    returning id,driver_id into v_task_id,v_driver_id;
    if v_task_id is not null and v_driver_id is not null and tg_op='UPDATE' then
      insert into public.notifications(user_id,order_id,title,body,type,link,message_params,source_event_key)
      values(v_driver_id,new.id,'Delivery schedule changed','The delivery schedule for order '||new.order_number||' was updated.',
        'driver_task_schedule_changed','/driver/task/'||v_task_id,
        jsonb_build_object('orderNumber',new.order_number,'taskType','delivery','scheduledFor',v_scheduled_for),
        'driver-task-schedule:'||v_task_id::text||':'||extract(epoch from clock_timestamp())::bigint::text)
      on conflict (user_id,order_id,source_event_key) where source_event_key is not null and order_id is not null do nothing;
    end if;
  end if;
  if new.status = 'cancelled' then
    insert into public.notifications(user_id,order_id,title,body,type,link,message_params,source_event_key)
    select t.driver_id,new.id,'Driver task cancelled','The '||t.task_type||' task for order '||new.order_number||' was cancelled.',
      'driver_task_cancelled','/driver/task/'||t.id,
      jsonb_build_object('orderNumber',new.order_number,'taskType',t.task_type),
      'driver-task-cancelled:'||t.id::text
    from public.driver_tasks t
    where t.order_id=new.id and t.driver_id is not null and t.task_status not in ('completed','cancelled')
    on conflict (user_id,order_id,source_event_key) where source_event_key is not null and order_id is not null do nothing;
    update public.driver_tasks set task_status = 'cancelled', cancelled_at = now(), updated_at = now()
    where order_id = new.id and task_status not in ('completed','cancelled');
    update public.order_live_locations set status = 'completed', ended_at = now(), updated_at = now()
    where order_id = new.id and status = 'active';
  end if;
  return new;
end;
$$;
revoke all on function public.sync_driver_tasks_from_order_v1() from public, anon, authenticated;
drop trigger if exists orders_sync_driver_tasks_v1 on public.orders;
create trigger orders_sync_driver_tasks_v1 after insert or update of status, pickup_date, pickup_start, delivery_eta on public.orders
for each row execute function public.sync_driver_tasks_from_order_v1();

-- Existing live orders are made task-aware without duplicating a leg.
select public.create_driver_task_v1(id, 'pickup') from public.orders
where not is_demo and collection_method = 'home_pickup' and status in (
  'accepted','pickup_in_progress','picked_up','received_at_store','processing','ready',
  'ready_for_collection','out_for_delivery','delivered','collected'
);
select public.create_driver_task_v1(id, 'delivery') from public.orders
where not is_demo and return_method = 'home_delivery' and status in ('ready','out_for_delivery','delivered');

update public.driver_tasks t set
  driver_id = o.assigned_driver_id,
  task_status = case
    when t.task_type = 'pickup' and o.status in ('picked_up','received_at_store','processing','ready','ready_for_collection','out_for_delivery','delivered','collected') then 'completed'
    when t.task_type = 'delivery' and o.status = 'delivered' then 'completed'
    when t.task_type = 'pickup' and o.status = 'pickup_in_progress' then case when o.assigned_driver_id is null then 'unassigned' else 'en_route' end
    when t.task_type = 'delivery' and o.status = 'out_for_delivery' then case when o.assigned_driver_id is null then 'unassigned' else 'en_route' end
    when o.assigned_driver_id is not null then 'assigned'
    else t.task_status end,
  assigned_at = case when o.assigned_driver_id is not null then coalesce(t.assigned_at, now()) else t.assigned_at end,
  completed_at = case
    when (t.task_type = 'pickup' and o.status in ('picked_up','received_at_store','processing','ready','ready_for_collection','out_for_delivery','delivered','collected'))
      or (t.task_type = 'delivery' and o.status = 'delivered') then coalesce(t.completed_at, o.updated_at)
    else t.completed_at end,
  updated_at = now()
from public.orders o where o.id = t.order_id;

create or replace function public.driver_task_payload_v1(p_task_id uuid, p_include_code boolean default false)
returns jsonb language sql stable security definer set search_path = public, pg_temp as $$
  select jsonb_build_object(
    'id', t.id, 'orderId', t.order_id, 'orderNumber', o.order_number,
    'driverId', t.driver_id, 'driverName', d.full_name,
    'taskType', t.task_type, 'taskStatus', t.task_status, 'scheduledFor', t.scheduled_for,
    'assignedAt', t.assigned_at, 'acceptedAt', t.accepted_at, 'startedAt', t.started_at,
    'arrivedAt', t.arrived_at, 'completedAt', t.completed_at,
    'customerName', c.full_name, 'customerPhone', coalesce(nullif(o.contact_phone,''), c.phone),
    'address', case when t.task_type = 'pickup' then o.pickup_address else o.delivery_address end,
    'instructions', o.pickup_instructions, 'itemSummary', o.item_summary,
    'latitude', case when t.task_type = 'pickup' then o.pickup_latitude else o.delivery_latitude end,
    'longitude', case when t.task_type = 'pickup' then o.pickup_longitude else o.delivery_longitude end,
    'verificationCode', case when p_include_code then v.verification_code else null end,
    'openIssue', case when public.is_admin() or t.driver_id = auth.uid() then
      (select jsonb_build_object('id', i.id, 'reason', i.reason, 'notes', i.notes, 'createdAt', i.created_at)
        from public.driver_task_issues i where i.task_id = t.id and i.status = 'open' order by i.created_at desc limit 1)
      else null end,
    'updatedAt', t.updated_at
  )
  from public.driver_tasks t
  join public.orders o on o.id = t.order_id
  join public.profiles c on c.id = o.user_id
  left join public.profiles d on d.id = t.driver_id
  left join public.driver_task_verifications v on v.task_id = t.id
  where t.id = p_task_id;
$$;
revoke all on function public.driver_task_payload_v1(uuid,boolean) from public, anon, authenticated;

create or replace function public.driver_tasks_list_v1(p_history boolean default false)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v_result jsonb;
begin
  if not public.is_driver() then raise exception 'DRIVER_REQUIRED'; end if;
  select coalesce(jsonb_agg(public.driver_task_payload_v1(t.id, false) order by
    case when t.task_status in ('en_route','arrived') then 0 when t.task_status in ('assigned','accepted') then 1 else 2 end,
    t.scheduled_for nulls last, t.created_at), '[]'::jsonb)
  into v_result from public.driver_tasks t
  where t.driver_id = auth.uid()
    and (case when p_history then t.task_status in ('completed','cancelled')
      else t.task_status in ('assigned','accepted','en_route','arrived','failed') end);
  return v_result;
end;
$$;

create or replace function public.driver_task_detail_v1(p_task_id uuid)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if not public.is_driver() or not exists (
    select 1 from public.driver_tasks where id = p_task_id and driver_id = auth.uid()
  ) then raise exception 'DRIVER_TASK_NOT_FOUND'; end if;
  return public.driver_task_payload_v1(p_task_id, false);
end;
$$;

create or replace function public.customer_order_driver_tasks_v1(p_order_id uuid)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v_result jsonb;
begin
  if auth.uid() is null or not exists (
    select 1 from public.orders where id = p_order_id and user_id = auth.uid()
  ) then raise exception 'ORDER_NOT_FOUND'; end if;
  select coalesce(jsonb_agg(public.driver_task_payload_v1(t.id, true) order by t.created_at), '[]'::jsonb)
  into v_result from public.driver_tasks t where t.order_id = p_order_id;
  return v_result;
end;
$$;

